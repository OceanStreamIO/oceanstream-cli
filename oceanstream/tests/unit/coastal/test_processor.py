"""End-to-end behaviour of :class:`CoastalProcessor`.

The scene here is synthetic but not invented: rho_b and depth are prescribed,
and Rrs is generated by the forward Lee model using the saved Sesimbra IOP fit,
so the pipeline runs in the optical regime it was built for.

What is being pinned is not "the numbers are right" — the golden regression
does that. It is the contract around a run: that a rejected scene still writes
its products and says why, that a failure mode gets its own status instead of
an exception escaping, that the outputs land on one grid, and that nothing
downstream can mistake a diagnostic run for a measurement.
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pytest

from oceanstream.coastal.aoi import AOI, BathymetryReference
from oceanstream.coastal.inversion.lee import forward_model
from oceanstream.coastal.io.rasters import RasterGrid, write_cog
from oceanstream.coastal.optics.qaa import SceneIOPs
from oceanstream.coastal.processor import (
    STATUS_EXECUTION_FAILED,
    STATUS_INSUFFICIENT_DATA,
    CoastalProcessor,
    InsufficientData,
    _depth_sign,
)
from oceanstream.coastal.products import STATUS_DIAGNOSTIC, STATUS_PUBLISHABLE
from oceanstream.coastal.scene import Scene

rasterio = pytest.importorskip("rasterio")

SOLAR_ZENITH_DEG = 21.0
SIZE = 48
#: Columns of shelf before the seaward drop-off.
SHELF_COLUMNS = 40
#: Sentinel-2 bands the processor needs: blue, blue-green, green, red,
#: red-edge, NIR, SWIR1, SWIR2. Both SWIR bands are required — the deep-water
#: screen keys on 2191 nm and the scene validator refuses to run without it.
BANDS_NM = (444.0, 489.0, 561.0, 667.0, 707.0, 835.0, 1612.0, 2191.0)


def test_registered_reference_is_applied_before_sampling(aoi, scene, tmp_path, monkeypatch):
    from dataclasses import replace

    from rasterio.warp import transform_geom

    from oceanstream.coastal.config import MaskConfig, RetrievalConfig
    from oceanstream.coastal.stages import prepare_scene

    # A small offshore patch has ample qualifying pixels, even when it is a
    # small fraction of the whole scene's deep-water population.
    patch = tmp_path / "reference.geojson"
    geometry = transform_geom(
        "EPSG:32629",
        "EPSG:4326",
        {
            "type": "Polygon",
            "coordinates": [
                [
                    [500460, 4255520],
                    [500480, 4255520],
                    [500480, 4256000],
                    [500460, 4256000],
                    [500460, 4255520],
                ]
            ],
        },
    )
    patch.write_text(
        json.dumps(
            {
                "type": "FeatureCollection",
                "features": [
                    {
                        "type": "Feature",
                        "properties": {},
                        "geometry": geometry,
                    }
                ],
            }
        )
    )
    registered = replace(
        aoi,
        deepwater_reference_uri=str(patch),
        metadata={
            "regions_preregistered": False,
            "reporting_area_provisional": True,
        },
    )
    monkeypatch.setattr(
        "oceanstream.coastal.stages.kd_map",
        lambda *args, **kwargs: np.ones(scene.shape, np.float32),
    )
    prepared = prepare_scene(registered, scene, mask_config=MaskConfig(deepwater_max_samples=50))
    assert prepared.deep.sum() == 50
    assert not prepared.deep[:, :46].any()
    assert prepared.provenance["coverage"]["deep_candidates_before_sampling"] == 96
    assert {"calibration_regions_exploratory", "reporting_area_provisional"} <= set(prepared.flags)
    failed = CoastalProcessor(config=RetrievalConfig(min_deep_pixels=10_000)).run(
        registered, scene, tmp_path / "failed"
    )
    assert failed.status == STATUS_INSUFFICIENT_DATA and not failed.success
    failure = json.loads((failed.output_dir / "failure.json").read_text())
    assert failure["diagnostics"]["depth_reference"]["coverage"]["deep_pixels"] == 96
    assert not (failed.output_dir / "manifest.json").exists()


def _transect(shelf_max_m: float) -> np.ndarray:
    """A shelf that shoals inshore, then a drop-off on the seaward edge.

    A single linear ramp cannot satisfy both ends of this pipeline. The QAA fit
    needs optically deep water — z > 30 m *and* z·Kd(490) > 6, so past ~70 m at
    Sesimbra — while the bottom retrieval needs water shallow enough for red
    light to make the round trip. So the shelf carries most of the grid and the
    last eight columns fall away to 140 m.
    """
    ramp = np.empty(SIZE, dtype=np.float64)
    ramp[:SHELF_COLUMNS] = np.linspace(0.5, shelf_max_m, SHELF_COLUMNS)
    ramp[SHELF_COLUMNS:] = np.linspace(40.0, 140.0, SIZE - SHELF_COLUMNS)
    return np.tile(ramp, (SIZE, 1))


def _single_band(iops: SceneIOPs, index: int) -> SceneIOPs:
    """One band's IOPs, so the forward model broadcasts against a 2-D grid."""
    return SceneIOPs(
        wavelengths_nm=iops.wavelengths_nm[index : index + 1],
        a=iops.a[index : index + 1],
        bb=iops.bb[index : index + 1],
        kd=iops.kd[index : index + 1],
        a_cdm_443=iops.a_cdm_443,
        bbp_555=iops.bbp_555,
        y=iops.y,
        n_deep_pixels=iops.n_deep_pixels,
        ref_wavelength_nm=iops.ref_wavelength_nm,
    )



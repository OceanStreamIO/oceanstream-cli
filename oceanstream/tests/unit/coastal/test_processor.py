class TestPhysics:
    def test_the_retrieval_recovers_the_prescribed_depth_gradient(self, result, truth_depth):
        with rasterio.open(result.products["sdb_depth"]) as src:
            depth = src.read(1)
        finite = np.isfinite(depth)
        assert finite.sum() > 0
        assert np.corrcoef(depth[finite], truth_depth[finite])[0, 1] > 0.9

    def test_shallow_water_lets_more_par_reach_the_seabed_than_deep(self, result):
        with rasterio.open(result.products["seabed_par"]) as src:
            par = src.read(1)
        assert np.nanmean(par[:, :8]) > np.nanmean(par[:, -8:])

    def test_the_detectability_margin_shrinks_with_depth(self, result):
        with rasterio.open(result.products["detectability_margin"]) as src:
            margin = src.read(1)
        assert np.nanmean(margin[:, :8]) > np.nanmean(margin[:, -8:])

    def test_the_two_prescribed_substrates_separate_into_classes(self, result):
        with rasterio.open(result.products["spectral_class"]) as src:
            labels = src.read(1)
        assert len(set(np.unique(labels)) - {-1}) >= 2

    def test_attenuation_is_reported_for_every_visible_band(self, result):
        payload = json.loads(Path(result.products["attenuation"]).read_text())
        bands = payload["attenuation"]["k_by_band"]
        assert len(bands) >= 4
        assert all(np.isfinite(v) for v in bands.values())



@pytest.fixture
def truth_depth() -> np.ndarray:
    """The reference surface: a 22 m shelf with a drop-off, positive down."""
    return _transect(22.0)


@pytest.fixture
def iops(scene_iops_raw: dict) -> SceneIOPs:
    """Full-spectrum Sesimbra IOPs interpolated onto the synthetic band set.

    Floored at pure water. The saved Sesimbra fit sits *below* the pure-water
    absorption floor at 667 nm and 707 nm — that is the known additive
    atmospheric-correction bias this library exists to flag, not a property of
    the sea. Generating a scene from it would produce Rrs no water column can
    make, and the retrieval would then correctly refuse to invert it. The floor
    keeps the synthetic experiment inside physics.
    """
    from oceanstream.coastal.optics import water

    source = np.asarray(scene_iops_raw["wavelengths_nm"], dtype=float)
    target = np.asarray(BANDS_NM, dtype=float)

    def resample(key: str) -> np.ndarray:
        return np.interp(target, source, np.asarray(scene_iops_raw[key], dtype=float))

    a = np.maximum(resample("a"), np.asarray(water.a_water(target), dtype=float))
    bb = np.maximum(resample("bb"), np.asarray(water.bb_water(target), dtype=float))

    return SceneIOPs(
        wavelengths_nm=target,
        a=a,
        bb=bb,
        kd=resample("kd"),
        a_cdm_443=float(scene_iops_raw.get("a_cdm_443") or np.nan),
        bbp_555=float("nan"),
        y=float("nan"),
        n_deep_pixels=5000,
        ref_wavelength_nm=561.0,
    )



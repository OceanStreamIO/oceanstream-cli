@pytest.fixture
def scene(grid: RasterGrid, truth_depth: np.ndarray, iops: SceneIOPs) -> Scene:
    """Rrs generated forward from a two-substrate seabed."""
    return _build_scene(grid, truth_depth, iops, noise_sigma=2e-5)


def _build_scene(
    grid: RasterGrid,
    depth: np.ndarray,
    iops: SceneIOPs,
    *,
    noise_sigma: float,
) -> Scene:
    rng = np.random.default_rng(20260627)
    n_bands = len(BANDS_NM)

    # Two substrates: bright sand and dark vegetation, in vertical stripes so
    # both are present at every depth.
    bright = np.array([0.10, 0.13, 0.17, 0.19, 0.20, 0.21, 0.0, 0.0])
    dark = np.array([0.02, 0.025, 0.045, 0.030, 0.055, 0.070, 0.0, 0.0])
    is_bright = (np.arange(SIZE)[None, :] // 6) % 2 == 0
    rho_b = np.where(
        is_bright[None, :, :],
        bright[:, None, None],
        dark[:, None, None],
    ).astype(np.float64)

    # forward_model broadcasts IOPs against the depth grid, so it has to be
    # driven one band at a time.
    rrs = np.stack(
        [
            forward_model(rho_b[i], depth, _single_band(iops, i), SOLAR_ZENITH_DEG)
            for i in range(n_bands)
        ]
    )
    rrs = rrs + rng.normal(0.0, noise_sigma, rrs.shape)

    # rhos: above-water surface reflectance. SWIR is dark over water, which is
    # what the composite mask keys on.
    rhos = np.clip(rrs * np.pi, 0.0, None)
    rhos[BANDS_NM.index(1612.0)] = 0.002
    rhos[BANDS_NM.index(2191.0)] = 0.001
    rhos[BANDS_NM.index(835.0)] = np.clip(rhos[BANDS_NM.index(835.0)], 0.0, 0.01)

    return Scene.from_arrays(
        wavelengths_nm=BANDS_NM,
        rrs_above=rrs,
        grid=grid,
        solar_zenith_deg=SOLAR_ZENITH_DEG,
        sensor="sentinel2",
        rhos=rhos,
        acquisition_date=None,
        metadata={"synthetic": True},
    )



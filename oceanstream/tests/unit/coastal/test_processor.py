class TestFailureModes:
    def test_an_aoi_without_bathymetry_is_insufficient_data_not_a_crash(self, scene, tmp_path):
        bare = AOI(name="no-bathy", processing_bbox=(-9.05, 38.40, -8.95, 38.48))
        result = CoastalProcessor().run(bare, scene, tmp_path / "out")
        assert result.status == STATUS_INSUFFICIENT_DATA
        assert not result.success
        assert "bathymetry" in result.message

    def test_the_insufficient_data_message_says_what_to_supply(self, scene, tmp_path):
        bare = AOI(name="no-bathy", processing_bbox=(-9.05, 38.40, -8.95, 38.48))
        result = CoastalProcessor().run(bare, scene, tmp_path / "out")
        assert "fine_bathymetry" in result.message

    def test_an_all_cloud_scene_is_insufficient_data(self, aoi, scene, grid, tmp_path):
        opaque = Scene.from_arrays(
            wavelengths_nm=BANDS_NM,
            rrs_above=scene.rrs_above,
            grid=grid,
            solar_zenith_deg=SOLAR_ZENITH_DEG,
            sensor="sentinel2",
            rhos=np.full_like(scene.rhos, 0.6),
        )
        result = CoastalProcessor().run(aoi, opaque, tmp_path / "out")
        assert result.status == STATUS_INSUFFICIENT_DATA
        assert "mask" in result.message.lower() or "pixel" in result.message.lower()

    def test_an_unexpected_error_is_reported_not_propagated(
        self, aoi, scene, tmp_path, monkeypatch
    ):
        def boom(*args, **kwargs):
            raise RuntimeError("kaboom")

        monkeypatch.setattr("oceanstream.coastal.optics.qaa.fit_scene_iops", boom, raising=True)
        result = CoastalProcessor().run(aoi, scene, tmp_path / "out")
        assert result.status == STATUS_EXECUTION_FAILED
        assert "kaboom" in result.message
        assert not result.success


class TestDepthSign:
    def test_a_positive_down_tag_is_believed(self, tmp_path, grid, truth_depth):
        path = tmp_path / "down.tif"
        write_cog(path, truth_depth.astype(np.float32), grid, tags={"positive": "down"})
        sign, source = _depth_sign(truth_depth, str(path))
        assert sign == 1.0
        assert "tag" in source

    def test_a_positive_up_tag_flips_the_sign(self, tmp_path, grid, truth_depth):
        path = tmp_path / "up.tif"
        write_cog(path, -truth_depth.astype(np.float32), grid, tags={"positive": "up"})
        sign, source = _depth_sign(-truth_depth, str(path))
        assert sign == -1.0

    def test_without_a_tag_the_median_decides(self, tmp_path, grid, truth_depth):
        path = tmp_path / "untagged.tif"
        write_cog(path, -truth_depth.astype(np.float32), grid)
        sign, source = _depth_sign(-truth_depth, str(path))
        assert sign == -1.0
        assert "median" in source

    def test_an_ambiguous_grid_is_refused_rather_than_guessed(self, tmp_path):
        near_zero = np.linspace(-0.5, 0.5, 100)
        with pytest.raises(InsufficientData, match="positive-up or positive-down"):
            _depth_sign(near_zero, str(tmp_path / "missing.tif"))

    def test_a_grid_with_no_overlap_says_so(self, tmp_path):
        with pytest.raises(InsufficientData, match="overlap"):
            _depth_sign(np.full(10, np.nan), str(tmp_path / "missing.tif"))



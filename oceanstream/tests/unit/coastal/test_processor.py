    def test_tide_correction_requires_acquisition_time_and_matching_datum(self, aoi, scene):
        import datetime as dt
        from dataclasses import replace

        from oceanstream.coastal.bathymetry.tide import TideCorrection
        from oceanstream.coastal.stages import prepare_scene

        when = dt.datetime.combine(scene.acquisition_date, dt.time(12), tzinfo=dt.UTC)
        configured = replace(scene, acquisition_datetime=when)
        tide = TideCorrection(
            1.0,
            "model",
            "test gauge",
            when=when,
            uncertainty_m=0.2,
            metadata={"vertical_datum": "LAT"},
        )
        corrected = prepare_scene(aoi, configured, tide=tide)
        original = prepare_scene(aoi, configured)
        np.testing.assert_allclose(corrected.depth, original.depth + 1)
        np.testing.assert_allclose(
            corrected.depth_sigma**2, original.depth_sigma**2 + 0.04, rtol=1e-5
        )
        assert "tide_correction_missing" not in corrected.flags
        with pytest.raises(ValueError, match="same timezone-aware acquisition time"):
            prepare_scene(aoi, scene, tide=tide)
        with pytest.raises(ValueError, match="datum"):
            prepare_scene(aoi, configured, tide=replace(tide, metadata={"vertical_datum": "MSL"}))


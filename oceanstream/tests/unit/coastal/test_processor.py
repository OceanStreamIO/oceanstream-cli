class TestRunCompletes:
    def test_the_run_does_not_raise(self, result):
        assert result.message, result.message

    def test_the_run_reports_one_of_the_four_defined_statuses(self, result):
        assert result.status in {
            "passed",
            "rejected",
            STATUS_INSUFFICIENT_DATA,
            STATUS_EXECUTION_FAILED,
        }

    def test_a_completed_run_is_marked_successful(self, result):
        assert result.success, result.message

    def test_success_and_acceptance_are_separate_questions(self, result):
        """A run can finish cleanly and still be inadmissible."""
        assert result.success
        assert result.accepted == (result.status == "passed")

    def test_the_campaign_and_aoi_are_carried_through(self, result):
        assert result.campaign_id == "unit-test"
        assert result.aoi_name == "synthetic-sesimbra"



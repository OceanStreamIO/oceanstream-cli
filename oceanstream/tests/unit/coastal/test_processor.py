    def test_output_stac_validates_against_every_declared_schema(self, result):
        import jsonschema
        from referencing import Registry, Resource
        from referencing.jsonschema import DRAFT7

        root = Path(__file__).resolve().parents[2] / "data" / "coastal" / "stac_schemas"
        schemas = {
            uri: json.loads((root / name).read_text())
            for uri, name in json.loads((root / "index.json").read_text()).items()
        }
        registry = Registry().with_resources(
            (uri, Resource.from_contents(schema, default_specification=DRAFT7))
            for uri, schema in schemas.items()
        )
        for path, core in ((result.stac_item, "item"), (result.stac_collection, "collection")):
            document = json.loads(path.read_text())
            url = f"https://schemas.stacspec.org/v1.0.0/{core}-spec/json-schema/{core}.json"
            for uri in [url, *document.get("stac_extensions", [])]:
                jsonschema.Draft7Validator(
                    schemas[uri], registry=registry, format_checker=jsonschema.FormatChecker()
                ).validate(document)

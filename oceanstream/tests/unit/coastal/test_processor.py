class TestProducts:
    def test_the_expected_products_are_written(self, result):
        for key in (
            "sdb_depth",
            "optical_depth",
            "seabed_par",
            "detectability_margin",
            "detectable",
            "spectral_class",
            "attenuation",
            "detectability",
            "iops",
            "qc",
            "report",
        ):
            assert key in result.products, f"missing {key}"

    def test_one_rho_b_raster_per_visible_band(self, result):
        rho_b_keys = {
            k
            for k in result.products
            if k.startswith("rho_b_") and not k.startswith("rho_b_sigma_")
        }
        assert rho_b_keys == {
            "rho_b_444",
            "rho_b_489",
            "rho_b_561",
            "rho_b_667",
        }

    def test_swir_never_becomes_a_benthic_product(self, result):
        assert "rho_b_1612" not in result.products
        assert "rho_b_2191" not in result.products

    def test_every_product_exists_on_disk(self, result):
        for key, href in result.products.items():
            assert Path(href).exists(), f"{key} at {href}"

    def test_every_raster_shares_the_run_grid(self, result, grid):
        for key, href in result.products.items():
            if not href.endswith(".tif"):
                continue
            with rasterio.open(href) as src:
                assert (src.width, src.height) == (grid.width, grid.height), key
                assert src.crs.to_string() == grid.crs, key

    def test_the_status_tag_matches_the_verdict(self, result):
        expected = STATUS_PUBLISHABLE if result.accepted else STATUS_DIAGNOSTIC
        with rasterio.open(result.products["sdb_depth"]) as src:
            assert src.tags()["OCEANSTREAM_STATUS"] == expected

    def test_the_provenance_reaches_the_rasters(self, result):
        with rasterio.open(result.products["sdb_depth"]) as src:
            tags = src.tags()
        assert tags["OCEANSTREAM_AOI"] == "synthetic-sesimbra"
        assert tags["OCEANSTREAM_CAMPAIGN_ID"] == "unit-test"
        assert float(tags["OCEANSTREAM_SOLAR_ZENITH_DEG"]) == pytest.approx(
            SOLAR_ZENITH_DEG, abs=1e-3
        )

    def test_the_class_raster_uses_negative_one_for_nodata_not_class_zero(self, result):
        with rasterio.open(result.products["spectral_class"]) as src:
            assert src.nodata == -1
            assert src.dtypes[0] == "int16"


